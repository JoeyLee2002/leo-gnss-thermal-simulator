function [items, nodes] = buildThermalReportDetails(bundle)
%BUILDTHERMALREPORTDETAILS Derive auditable analyses from the retained epochs.
items = struct('stage', {}, 'titleZh', {}, 'titleEn', {}, ...
    'linesZh', {}, 'linesEn', {}, 'figureStem', {}, 'charts', {});
nodes = table;
if ~isfield(bundle, 'scenario') || ~isstruct(bundle.scenario), return; end
r = bundle.scenario;
if ~all(isfield(r, {'timeS','temperatureK','network','loads','orbit'})), return; end
t = r.timeS(:); T = r.temperatureK; n = r.network;
if numel(t) < 2 || size(T,1) ~= numel(t) || any(diff(t) <= 0) ...
        || any(~isfinite(t)) || any(~isfinite(T(:)))
    error('leotherm:ReportHistory', 'Detailed report requires finite, ordered thermal history.');
end
count = size(T,2); ids = (1:count)'; h = (t-t(1))/3600;
span = max(T,[],1)-min(T,[],1); meanT = trapz(t,T,1)/(t(end)-t(1));
nodes = table(ids, string(n.nodeNames(:)), min(T,[],1)', meanT', ...
    max(T,[],1)', span', T(end,:)'-T(1,:)', n.capacityJK(:), ...
    n.internalPowerW(:), 'VariableNames', {'node_id','node_name','minimum_k', ...
    'time_mean_k','maximum_k','peak_to_peak_k','end_minus_start_k', ...
    'capacity_j_per_k','configured_internal_power_w'});
[~, order] = sort(span,'descend'); selected = sort(order(1:min(12,count)));
zhNames = leotherm.nodeDisplayNames(n.nodeNames,'zh');
enNames = leotherm.nodeDisplayNames(n.nodeNames,'en');
namesZh = arrayfun(@(k) sprintf('%d %s',k,zhNames{k}),selected,'UniformOutput',false);
namesEn = arrayfun(@(k) sprintf('%d %s',k,enNames{k}),selected,'UniformOutput',false);
notesZh = sprintf('图示 %d/%d 个节点，按温度最大值减最小值排序选取；全节点统计见附表。',numel(selected),count);
notesEn = sprintf('%d/%d nodes plotted, selected by full temperature range; all are tabulated.',numel(selected),count);
period = r.orbit.periodS; cycles = (t(end)-t(1))/period;
if max(diff(t))-min(diff(t)) > 1e-8*max(diff(t))
add('coverage','时间覆盖与分析分辨率','Time coverage and resolution', ...
    {sprintf('保留 %d 个历元，跨度 %.3f h，覆盖约 %.2f 圈。',numel(t),h(end),cycles), ...
    sprintf('采样间隔为 %.3g 至 %.3g s；图中不补齐或插值缺失观测。',min(diff(t)),max(diff(t))), ...
    sprintf('共覆盖 %.2f 圈，变化的采样间隔如下图。',cycles)}, ...
    {sprintf('%d retained epochs span %.3f h, approximately %.2f orbits.',numel(t),h(end),cycles), ...
    sprintf('Output spacing: %.3g to %.3g s. No missing observations are filled.',min(diff(t)),max(diff(t))), ...
    sprintf('The history covers %.2f orbits; changing sample spacing is plotted below.',cycles)}, ...
    chart('line',h(2:end),diff(t),'分析时间 / h','Analysis time / h','采样间隔 / s','Sample interval / s',{'采样间隔'},{'Sample interval'}));
end
[maxCapacity,capacityNode] = max(n.capacityJK);
[maxPower,powerNode] = max(n.internalPowerW);
add('capacity','热容与内部功耗','Thermal capacity and internal power', ...
    {sprintf('网络包含 %d 个节点，总热容 %.5g J/K，配置内部功耗 %.5g W。',count,sum(n.capacityJK),sum(n.internalPowerW)), ...
    sprintf('%s 热容最大：%.5g J/K，占总热容 %.1f%%。',zhNames{capacityNode},maxCapacity,100*maxCapacity/sum(n.capacityJK)), ...
    sprintf('%s 配置功耗最高：%.4g W。',zhNames{powerNode},maxPower),notesZh}, ...
    {sprintf('%d nodes; total capacity %.5g J/K; configured internal power %.5g W.',count,sum(n.capacityJK),sum(n.internalPowerW)), ...
    sprintf('%s has the largest capacity: %.5g J/K (%.1f%% of total).',enNames{capacityNode},maxCapacity,100*maxCapacity/sum(n.capacityJK)), ...
    sprintf('%s has the highest configured power: %.4g W.',enNames{powerNode},maxPower),notesEn}, ...
    [chart('bar',selected,n.capacityJK(selected),'节点编号','Node ID','热容 / J/K','Capacity / J/K',{},{}), ...
    chart('bar',selected,n.internalPowerW(selected),'节点编号','Node ID','配置功耗 / W','Configured power / W',{}, {})]);
G = n.conductanceWK; links = nnz(triu(G>0,1)); pick = 1:min(30,count);
[degree,hub] = max(sum(G>0,2));
add('conductance','节点连接与导热路径','Thermal links and conductance', ...
    {sprintf('网络含 %d 条导热连接；%s 与 %d 个节点相连，是连接最多的节点。',links,zhNames{hub},degree), ...
    sprintf('图示前 %d/%d 个节点的连接关系，线越粗表示热导越大。',numel(pick),count), ...
    '连线布局表示热传导路径，而非卫星几何外形；各连接的热导值见连接表 CSV。'}, ...
    {sprintf('%d conductive links; %s has the most connections (%d).',links,enNames{hub},degree), ...
    sprintf('First %d/%d nodes shown; thicker lines indicate larger conductance.',numel(pick),count), ...
    'The layout depicts thermal connectivity, not spacecraft geometry. Conductances are listed in the link CSV.'}, ...
    chart('network',pick,G(pick,pick),'','','','',{},{}));
internal = find(n.projectedAreaM2==0 & n.radiatingAreaM2==0);
optZh = {sprintf('对外辐射面积合计 %.4g m^2；图中明确标注零值。',sum(n.radiatingAreaM2)),notesZh};
optEn = {sprintf('Total external radiating area: %.4g m^2. Zero values are explicitly labelled.',sum(n.radiatingAreaM2)),notesEn};
if ~isempty(internal)
    optZh{end+1} = sprintf('%s 的投影面积和对外辐射面积均设为 0，通过导热连接交换热量。',strjoin(zhNames(internal),'、'));
    optEn{end+1} = sprintf('%s have zero projected and external radiating areas and exchange heat through conductive links.',strjoin(enNames(internal),', '));
end
add('optics','光学参数与辐射面积','Optical properties and radiating area', ...
    optZh,optEn, ...
    [chart('bar',selected,[n.solarAbsorptivity(selected),n.irEmissivity(selected)],'节点编号','Node ID','无量纲系数','Dimensionless coefficient',{'太阳吸收率','红外发射率'},{'Solar absorptivity','IR emissivity'}), ...
    chart('bar',selected,n.radiatingAreaM2(selected),'节点编号','Node ID','辐射面积 / m^2','Radiating area / m^2',{}, {})]);
v = r.loads.visibleFraction; fraction = trapz(t,double(v<0.999))/(t(end)-t(1));
add('illumination','轨道光照与入影结构','Illumination and eclipse structure', ...
    {sprintf('按历元间梯形积分估算，部分或完全入影占分析时长的 %.2f%%。',100*fraction), ...
    sprintf('太阳可见比例范围 %.3f 至 %.3f；平均轨道周期 %.2f min。',min(v),max(v),period/60), ...
    '部分入影阈值为太阳可见比例小于 0.999；采样占比与时间加权占比可能不同。', ...
    sprintf('本段入影 %d 次、出影 %d 次；β角范围 %.3f 至 %.3f 度。',nnz(diff(v<0.999)==1),nnz(diff(v<0.999)==-1),min(r.orbit.betaDeg),max(r.orbit.betaDeg))}, ...
    {sprintf('Trapezoidal time weighting estimates partial/full eclipse over %.2f%% of the window.',100*fraction), ...
    sprintf('Solar visibility ranges from %.3f to %.3f; orbital period %.2f min.',min(v),max(v),period/60), ...
    'Eclipse uses visibility below 0.999. Time-weighted and epoch-count fractions can differ.', ...
    sprintf('%d eclipse entries and %d exits; beta angle %.3f to %.3f deg.',nnz(diff(v<0.999)==1),nnz(diff(v<0.999)==-1),min(r.orbit.betaDeg),max(r.orbit.betaDeg))}, ...
    [chart('line',h,v,'分析时间 / h','Analysis time / h','太阳可见比例','Solar visibility',{'可见比例'},{'Visibility'}), ...
    chart('line',h,r.orbit.betaDeg,'分析时间 / h','Analysis time / h','太阳高度角 / deg','Beta angle / deg',{'轨道太阳高度角'},{'Beta angle'})]);
q = [sum(r.loads.directSolarW,2),sum(r.loads.albedoW,2),sum(r.loads.earthIRW,2)];
mq = trapz(t,q,1)/(t(end)-t(1));
add('heat_inputs','环境热流组成与变化','Environmental heat inputs', ...
    {sprintf('时间平均吸收功率：太阳直射 %.3f W，反照 %.3f W，地球红外 %.3f W。',mq), ...
    '曲线表示全网络吸收功率之和，已经包含节点面积和相应吸收特性。', ...
    sprintf('太阳直射吸收功率 %.3f 至 %.3f W；地球红外 %.3f 至 %.3f W。',min(q(:,1)),max(q(:,1)),min(q(:,3)),max(q(:,3)))}, ...
    {sprintf('Time-mean absorbed power: solar %.3f W; albedo %.3f W; Earth IR %.3f W.',mq), ...
    'Curves sum absorbed power over the network, including area and absorption properties.', ...
    sprintf('Solar absorbed power %.3f to %.3f W; Earth IR %.3f to %.3f W.',min(q(:,1)),max(q(:,1)),min(q(:,3)),max(q(:,3)))}, ...
    chart('line',h,q,'分析时间 / h','Analysis time / h','吸收功率 / W','Absorbed power / W',{'太阳直射','地球反照','地球红外'},{'Direct solar','Earth albedo','Earth IR'}));
[peak,hot] = max(max(T,[],1)); [cold,low] = min(min(T,[],1));
add('temperatures','节点温度与极值','Nodal temperatures and extrema', ...
    {sprintf('全窗口最高 %.3f K（%.2f 摄氏度，节点 %d），最低 %.3f K（%.2f 摄氏度，节点 %d）。',peak,peak-273.15,hot,cold,cold-273.15,low), ...
    sprintf('最大完整峰峰差 %.3f K（节点 %d）。这里使用最大值减最小值，不是 95%%-5%% 分位跨度。',max(span),order(1)), ...
    sprintf('最高温节点为 %s，最低温节点为 %s。',zhNames{hot},zhNames{low}),notesZh}, ...
    {sprintf('Window maximum %.3f K (%.2f deg C, node %d); minimum %.3f K (%.2f deg C, node %d).',peak,peak-273.15,hot,cold,cold-273.15,low), ...
    sprintf('Largest full peak-to-peak range %.3f K (node %d), distinct from a 95th-5th percentile span.',max(span),order(1)), ...
    sprintf('Hottest node: %s; coldest node: %s.',enNames{hot},enNames{low}),notesEn}, ...
    chart('line',h,T(:,selected),'分析时间 / h','Analysis time / h','温度 / K','Temperature / K',namesZh,namesEn));
spread = max(T,[],2)-min(T,[],2);
[ii,jj] = find(triu(G>0,1)); flux = zeros(numel(t),1);
for k = 1:numel(ii), flux = max(flux,abs(G(ii(k),jj(k))*(T(:,ii(k))-T(:,jj(k))))); end
add('gradients','节点温差与导热负荷','Temperature differences and link heat flow', ...
    {sprintf('同时刻全网络最大温差 %.3f K；最大单连接热流绝对值 %.3f W。',max(spread),max(flux)), ...
    '上下图分别为每个历元的最大节点温差和最大单连接热流包络。', ...
    sprintf('本段含 %d 条导热连接；包络逐历元从这些连接中取最大值。',numel(ii))}, ...
    {sprintf('Maximum simultaneous nodal spread %.3f K; maximum absolute single-link flow %.3f W.',max(spread),max(flux)), ...
    'Panels show epoch-wise temperature spread and the largest absolute link heat flow.', ...
    sprintf('The envelope takes the largest value across %d conductive links at each epoch.',numel(ii))}, ...
    [chart('line',h,spread,'分析时间 / h','Analysis time / h','最大温差 / K','Maximum difference / K',{'全节点温差'},{'Nodal spread'}), ...
    chart('line',h,flux,'分析时间 / h','Analysis time / h','最大连接热流 / W','Maximum link flow / W',{'绝对热流包络'},{'Absolute flow envelope'})]);
stored = (T-T(1,:))*n.capacityJK(:); ledger = [];
if isfield(r,'numerics') && isfield(r.numerics,'integratedNetHeatJ')
    ledger = r.numerics.integratedNetHeatJ(:);
    if numel(ledger) ~= numel(t) || any(~isfinite(ledger)), ledger = []; end
end
if isempty(ledger)
    ey = stored/1000; legendsZh = {'储能变化'}; legendsEn = {'Stored energy change'};
    balanceZh = '未提供与分析历元对齐的独立热量账本，不能判断能量闭合。';
    balanceEn = 'No aligned independent heat ledger is available; closure cannot be assessed.';
else
    ledger = ledger-ledger(1); ey = [stored,ledger]/1000;
    legendsZh = {'储能变化','求解器积分净热量'}; legendsEn = {'Stored energy change','Integrated net heat'};
    balanceZh = sprintf('从分析起点重新计零后，最大累计闭合差 %.5g J。',max(abs(stored-ledger)));
    balanceEn = sprintf('After rebasing both at the analysis start, maximum cumulative closure is %.5g J.',max(abs(stored-ledger)));
end
add('energy_balance','储能变化与能量守恒','Stored energy and energy balance', ...
    {balanceZh, '储能变化为各节点热容乘温度变化的总和；预热阶段不计入本图零点。', ...
    '平衡关系：储能变化 = 外部吸热 + 内部发热 - 辐射散热 + 边界输入。', ...
    sprintf('分析末端储能变化 %.5g kJ。',stored(end)/1000)}, ...
    {balanceEn, 'Stored energy is the sum of capacity times temperature change, relative to analysis start.', ...
    'Balance: stored energy = external heat + internal heat - radiation + boundary heat.', ...
    sprintf('End-of-window stored-energy change: %.5g kJ.',stored(end)/1000)}, ...
    chart('line',h,ey,'分析时间 / h','Analysis time / h','累计能量 / kJ','Cumulative energy / kJ',legendsZh,legendsEn));
if isfield(n,'roles') && isfield(n.roles,'response')
    response = n.roles.response;
else
    response = find(strcmp(n.nodeNames,'gnss_rf_frontend'),1);
end
phase = leotherm.reportPeakLag(r);
harmonic=leotherm.reportHarmonicResponse(r);
if ~isempty(harmonic) && harmonic.available
    add('orbital_response','轨道周期热响应','Orbital thermal response', ...
        {sprintf('全网络外部吸热与 %s 温度的轨道基频等效相位时延为 %.2f s（%.2f min）。',zhNames{response},harmonic.phaseDelayS,harmonic.phaseDelayS/60), ...
        sprintf('基频幅值：热流 %.3f W，温度 %.3f K；前后半段各自估计的相位时延相差 %.2f s。',harmonic.forcingAmplitudeW,harmonic.responseAmplitudeK,harmonic.halfWindowDifferenceS), ...
        '对实际历元同时拟合常数、趋势和前三阶轨道谐波，提取基频相位差；下图为各自基频分量除以幅值后的对比。'}, ...
        {sprintf('Orbital-frequency phase delay between total external heat and %s temperature: %.2f s (%.2f min).',enNames{response},harmonic.phaseDelayS,harmonic.phaseDelayS/60), ...
        sprintf('Fundamental amplitudes: %.3f W and %.3f K. Separate half-window estimates differ by %.2f s.',harmonic.forcingAmplitudeW,harmonic.responseAmplitudeK,harmonic.halfWindowDifferenceS), ...
        'Offset, trend and three harmonics are fitted jointly at actual epochs. Curves show amplitude-normalized fundamental components.'}, ...
        chart('line',h,[harmonic.forcingFundamental/harmonic.forcingAmplitudeW,harmonic.responseFundamental/harmonic.responseAmplitudeK], ...
        '分析时间 / h','Analysis time / h','归一化基频分量','Normalized fundamental',{'外部吸热','响应温度'},{'External heat','Response temperature'}));
end
if ~isempty(phase)
    p = phase.signedPeakPhaseByCycleS;
    add('lag_detail','逐圈峰值时间差','Per-orbit peak timing', ...
        {sprintf('响应节点：%s。',zhNames{response}),leotherm.reportLagExplanation(phase,'zh'), ...
        sprintf('比较全网络外部吸热峰值与响应温度峰值，时间差折叠到 ±半个轨道周期（%.1f s）。',period/2), ...
        '正值表示折叠后的温度峰值较晚，负值较早；逐圈保留两种方向。'}, ...
        {sprintf('Response node: %s.',enNames{response}),leotherm.reportLagExplanation(phase,'en'), ...
        sprintf('Network external-heat peaks versus response-temperature peaks; differences wrap to +/- half an orbit (%.1f s).',period/2), ...
        'Positive values indicate later wrapped temperature peaks; negative values indicate earlier peaks. Both are retained.'}, ...
        chart('phase',phase.scoredCycleNumbers,p,'轨道周期编号','Orbit cycle','折叠峰值时间差 / s','Wrapped peak difference / s',{'逐圈时间差'},{'Per-orbit difference'}));
end
convZh = '没有周期稳态验收记录。'; convEn = 'No periodic-state acceptance record is available.';
if isfield(r,'convergence')
    c = r.convergence;
    if c.enabled
        if c.converged, stateZh='达到'; stateEn='met'; else, stateZh='未达到'; stateEn='did not meet'; end
        convZh = sprintf('冻结太阳条件下初始化 %g 圈，周期温差 %s K，%s所配置收敛条件。',c.cycles,num(c.periodicErrorK),stateZh);
        convEn = sprintf('Frozen-Sun initialization: %g cycles; periodic difference %s K; %s the configured criterion.',c.cycles,num(c.periodicErrorK),stateEn);
    else
        convZh = sprintf('使用固定预热 %g 圈，未执行周期稳态收敛验收。',c.cycles);
        convEn = sprintf('Fixed warmup: %g orbits. Periodic-state convergence was not tested.',c.cycles);
    end
end
add('initial_state','初始状态与温度漂移','Initial state and temperature drift', ...
    {convZh, sprintf('分析末端相对起点最大绝对温变 %.3f K。',max(abs(T(end,:)-T(1,:)))), ...
    sprintf('分析起止相隔 %.3f 圈；曲线以分析起点温度为零点。',cycles),notesZh}, ...
    {convEn, sprintf('Largest absolute end-minus-start temperature change %.3f K.',max(abs(T(end,:)-T(1,:)))), ...
    sprintf('Endpoints are %.3f orbits apart; curves are relative to analysis-start temperatures.',cycles),notesEn}, ...
    chart('line',h,T(:,selected)-T(1,selected),'分析时间 / h','Analysis time / h','相对初温变化 / K','Change from initial state / K',namesZh,namesEn));

    function add(stage,zh,en,lzh,len,charts)
        for j = 1:numel(charts)
            charts(j).nodeLabelsZh = {}; charts(j).nodeLabelsEn = {}; charts(j).nodeKeys = {};
            if ismember(charts(j).kind,{'bar','network'})
                at = charts(j).x;
                charts(j).nodeLabelsZh = arrayfun(@(k) sprintf('%d %s',k,zhNames{k}),at,'UniformOutput',false);
                charts(j).nodeLabelsEn = arrayfun(@(k) sprintf('%d %s',k,enNames{k}),at,'UniformOutput',false);
                charts(j).nodeKeys = n.nodeNames(at);
            end
        end
        items(end+1) = struct('stage',stage,'titleZh',zh,'titleEn',en, ...
            'linesZh',{lzh},'linesEn',{len},'figureStem',['detail_' stage],'charts',charts);
    end
end

function c = chart(kind,x,y,xzh,xen,yzh,yen,lzh,len)
c = struct('kind',kind,'x',x,'y',y,'xZh',xzh,'xEn',xen, ...
    'yZh',yzh,'yEn',yen,'legendZh',{lzh},'legendEn',{len});
end

function out = num(x)
if isfinite(x), out = sprintf('%.5g',x); else, out = 'NaN'; end
end
