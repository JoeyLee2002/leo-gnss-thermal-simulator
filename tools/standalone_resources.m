function [resources, relativePaths] = standalone_resources(root)
%STANDALONE_RESOURCES File-only allowlist for the MATLAB Runtime archive.
if nargin < 1, root = fileparts(fileparts(mfilename('fullpath'))); end
validateattributes(root, {'char','string'}, {'nonempty'});
root = char(java.io.File(char(root)).getCanonicalPath());

% Keep every engine source for dynamic adapters and paper source hashing.
source = dir(fullfile(root, 'src', '**', '*.m'));
source = source(~[source.isdir]);
if isempty(source)
    error('leotherm:StandaloneBuild', 'Engine sources are missing: %s', root);
end
sourcePaths = cell(numel(source), 1);
for k = 1:numel(source)
    filename = fullfile(source(k).folder, source(k).name);
    sourcePaths{k} = strrep(filename(numel(root)+2:end), filesep, '/');
end

% Runtime inputs only: no reports, archive evidence, docs or generated images.
relativePaths = [sort(sourcePaths); { ...
    'VERSION'; ...
    'templates/01_first_simulation.json'; ...
    'templates/02_thermal_lag.json'; ...
    'templates/03_satmo_benchmark.json'; ...
    'templates/04_telemetry_validation.json'; ...
    'examples/projects/01_first_simulation.mat'; ...
    'examples/projects/02_thermal_lag_24h.mat'; ...
    'examples/projects/03_physical_sweep.mat'; ...
    'examples/projects/04_telemetry_validation.mat'; ...
    'examples/projects/05_3d_geometry.mat'; ...
    'examples/projects/06_surface_volume_coupled.mat'; ...
    'examples/projects/06_engineering_model_exchange.json'; ...
    'examples/assets/example_tetrahedron.obj'; ...
    'examples/assets/example_two_tetrahedra.msh'; ...
    'examples/assets/example_coupled_surface.obj'; ...
    'examples/telemetry_templates/orbit_template.csv'; ...
    'examples/telemetry_templates/heat_template.csv'; ...
    'examples/telemetry_templates/validation_template.csv'; ...
    'studies/softwarex/sweep36/paper_example_revision4.m'; ...
    'studies/softwarex/sweep36/run_paper_sweep36_v129.m'; ...
    'studies/softwarex/sweep36/audit_sweep36_v129.m'; ...
    'studies/softwarex/sweep36/export_sweep36_open_data.m'; ...
    'studies/softwarex/sweep36/make_sweep36_figure_v129.m'; ...
    'studies/softwarex/sweep36/sweep36_protocol.m'; ...
    'studies/softwarex/sweep36/sweep36_readable_protocol.m'; ...
    'studies/softwarex/sweep36/sweep36_case.m'; ...
    'studies/softwarex/sweep36/sweep36_validate_case.m'; ...
    'studies/softwarex/sweep36/sweep36_paths.m'; ...
    'studies/softwarex/sweep36/sweep36_safe_output.m'; ...
    'studies/softwarex/sweep36/sweep36_source_fingerprint.m'; ...
    'studies/softwarex/sweep36/sweep36_file_sha256.m'; ...
    'studies/softwarex/sweep36/sweep36_write_json.m'}];
resources = cell(size(relativePaths));
for k = 1:numel(relativePaths)
    relative = relativePaths{k};
    if any(double(relative) < 32 | double(relative) > 126)
        error('leotherm:StandaloneBuild', 'Non-ASCII bundled resource: %s', relative);
    end
    resources{k} = fullfile(root, strrep(relative, '/', filesep));
    if ~isfile(resources{k})
        error('leotherm:StandaloneBuild', 'Missing bundled resource: %s', resources{k});
    end
end
end
