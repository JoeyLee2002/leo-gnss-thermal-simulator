function sweep36_validate_case(result,scenario,network)
%SWEEP36_VALIDATE_CASE Verify cached inputs and complete periodic outputs.
assert(isequaln(result.scenario,scenario) && isequaln(result.network,network), ...
    'sweep36:CacheMismatch','Saved case inputs differ from the requested case.');
assert(result.convergence.converged && result.convergence.periodicErrorK<=1e-3, ...
    'sweep36:NotConverged','Periodic initialization did not meet the study tolerance.');
assert(all(isfinite(result.temperatureK(:))) && ...
    result.metrics.orbitalPhaseAvailable && isfinite(result.metrics.orbitalPhaseDelayS), ...
    'sweep36:InvalidResult','Temperature or harmonic-delay outputs are invalid.');
assert(abs(result.timeS(end)/result.orbit.periodS-6)<1e-10 && ...
    all(diff(result.timeS)>0),'sweep36:IncompleteArc','Expected six complete analysis orbits.');
assert(abs(result.timeS(end)-scenario.durationS)<1e-7, ...
    'sweep36:IncompleteArc','Saved result duration differs from the requested duration.');
end
